"""UVM testbench and UVM register model (RAL) generators.

    uvm_testbench(module, prefix=None, num_items=20) -> {"files": {name: code}, "top", "prefix", "notes"}
    uvm_ral(regmap)                                  -> {"files": {name: code}, "block"}

The testbench is a complete, compilable skeleton (interface with clocking blocks, sequence item,
sequence, driver, monitor, agent, scoreboard with a reference-model hook, functional coverage,
environment, base test, tb_top and a file list). Only the reference model is left as a TODO.
"""

import datetime
import re

from .tb_generator import classify, reset_active_low


def _rng(width):
    return f"[{width - 1}:0] " if width and width > 1 else ""


def _banner(title, what):
    return (f"// {title}\n// {what}\n// Generated by VLSI Toolkit on {datetime.date.today()}\n"
            "// ----------------------------------------------------------------------------\n")


def _ident(s):
    s = re.sub(r"\W", "_", s)
    return s if re.match(r"[A-Za-z_]", s) else "m_" + s


# ============================================================================ testbench

def uvm_testbench(module, prefix=None, num_items=20):
    p = _ident(prefix or module.name)
    clocks, resets, data_in = classify(module)
    outputs = list(module.outputs)
    inouts = list(module.inouts)
    clk = clocks[0].name if clocks else None
    notes = []
    if not clk:
        notes.append("No clock input found: tb_top generates a clock for the interface; the DUT is combinational.")
    if len(clocks) > 1:
        notes.append(f"Several clocks ({', '.join(c.name for c in clocks)}): all are driven from one clock; give each its own if they are asynchronous.")
    if inouts:
        notes.append(f"Inout ports ({', '.join(x.name for x in inouts)}) are declared in the interface but not driven.")
    if not data_in:
        notes.append("The module has no data inputs, so the sequence item has no random fields.")

    files = {}
    cname = clk or "clk"

    # ---------------------------------------------------------------- interface
    sig = []
    for r in resets:
        sig.append(f"  logic {r.name};")
    for x in data_in + outputs + inouts:
        sig.append(f"  logic {_rng(x.width)}{x.name};")
    drv_out = "".join(f"\n    output {x.name};" for x in data_in)
    drv_in = "".join(f"\n    input  {x.name};" for x in outputs)
    mon_in = "".join(f"\n    input  {x.name};" for x in data_in + outputs + resets)
    files[f"{p}_if.sv"] = _banner(f"{p}_if", f"Interface for module {module.name}") + f"""
interface {p}_if (input logic {cname});
{chr(10).join(sig) if sig else "  // no data ports"}

  // driver side: drive inputs one cycle at a time, sample outputs just before the edge
  clocking drv_cb @(posedge {cname});
    default input #1step output #1;{drv_out}{drv_in}
  endclocking

  // monitor side: sample everything
  clocking mon_cb @(posedge {cname});
    default input #1step;{mon_in}
  endclocking

  modport DRV (clocking drv_cb{"".join(", output " + r.name for r in resets)});
  modport MON (clocking mon_cb);
endinterface
"""

    # ---------------------------------------------------------------- sequence item
    rand_fields = "\n".join(f"  rand logic {_rng(x.width)}{x.name};" for x in data_in) or "  // no data inputs"
    out_fields = "\n".join(f"       logic {_rng(x.width)}{x.name};   // observed" for x in outputs) or "  // no outputs"
    fmt = " ".join(f"{x.name}=%0h" for x in data_in + outputs) or "(no fields)"
    args = ", ".join(x.name for x in data_in + outputs)
    copy = "\n".join(f"    {x.name} = rhs_.{x.name};" for x in data_in + outputs)
    cmp = " && ".join(f"{x.name} === rhs_.{x.name}" for x in data_in + outputs) or "1"
    files[f"{p}_seq_item.sv"] = _banner(f"{p}_seq_item", "One stimulus/observation transaction") + f"""
class {p}_seq_item extends uvm_sequence_item;
  `uvm_object_utils({p}_seq_item)

{rand_fields}
{out_fields}

  // add constraints here, e.g.  constraint c_legal {{ opcode inside {{[0:5]}}; }}

  function new(string name = "{p}_seq_item");
    super.new(name);
  endfunction

  virtual function string convert2string();
    return $sformatf("{fmt}"{", " + args if args else ""});
  endfunction

  virtual function void do_copy(uvm_object rhs);
    {p}_seq_item rhs_;
    if (!$cast(rhs_, rhs)) `uvm_fatal("COPY", "type mismatch")
    super.do_copy(rhs);
{copy if copy else "    // nothing to copy"}
  endfunction

  virtual function bit do_compare(uvm_object rhs, uvm_comparer comparer);
    {p}_seq_item rhs_;
    if (!$cast(rhs_, rhs)) return 0;
    return super.do_compare(rhs, comparer) && {cmp};
  endfunction
endclass
"""

    # ---------------------------------------------------------------- sequence
    files[f"{p}_sequence.sv"] = _banner(f"{p}_sequence", "Random stimulus") + f"""
class {p}_base_seq extends uvm_sequence #({p}_seq_item);
  `uvm_object_utils({p}_base_seq)

  rand int unsigned num_items = {num_items};
  constraint c_num {{ num_items inside {{[1:1000]}}; }}

  function new(string name = "{p}_base_seq");
    super.new(name);
  endfunction

  virtual task body();
    repeat (num_items) begin
      req = {p}_seq_item::type_id::create("req");
      start_item(req);
      if (!req.randomize()) `uvm_error("RAND", "randomization failed")
      finish_item(req);
    end
  endtask
endclass
"""

    # ---------------------------------------------------------------- driver
    idle = "\n".join(f"    vif.drv_cb.{x.name} <= '0;" for x in data_in) or "    // no inputs to drive"
    drive = "\n".join(f"      vif.drv_cb.{x.name} <= req.{x.name};" for x in data_in) or "      // no inputs to drive"
    wait_reset = ""
    if resets:
        r = resets[0]
        level = "1'b1" if reset_active_low(r) else "1'b0"
        wait_reset = f"\n    wait (vif.{r.name} === {level});   // reset released\n    @(vif.drv_cb);"
    files[f"{p}_driver.sv"] = _banner(f"{p}_driver", "Drives one sequence item per clock") + f"""
class {p}_driver extends uvm_driver #({p}_seq_item);
  `uvm_component_utils({p}_driver)

  virtual {p}_if vif;

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  virtual function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    if (!uvm_config_db#(virtual {p}_if)::get(this, "", "vif", vif))
      `uvm_fatal("NOVIF", "virtual interface 'vif' not set")
  endfunction

  virtual task run_phase(uvm_phase phase);
{idle}{wait_reset}
    forever begin
      seq_item_port.get_next_item(req);
      @(vif.drv_cb);
{drive}
      seq_item_port.item_done();
    end
  endtask
endclass
"""

    # ---------------------------------------------------------------- monitor
    sample = "\n".join(f"      tr.{x.name} = vif.mon_cb.{x.name};" for x in data_in + outputs) or "      // nothing to sample"
    in_reset = ""
    if resets:
        r = resets[0]
        level = "1'b0" if reset_active_low(r) else "1'b1"
        in_reset = f"\n      if (vif.mon_cb.{r.name} === {level}) continue;   // in reset"
    files[f"{p}_monitor.sv"] = _banner(f"{p}_monitor", "Samples the interface every clock") + f"""
class {p}_monitor extends uvm_monitor;
  `uvm_component_utils({p}_monitor)

  virtual {p}_if vif;
  uvm_analysis_port #({p}_seq_item) ap;

  function new(string name, uvm_component parent);
    super.new(name, parent);
    ap = new("ap", this);
  endfunction

  virtual function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    if (!uvm_config_db#(virtual {p}_if)::get(this, "", "vif", vif))
      `uvm_fatal("NOVIF", "virtual interface 'vif' not set")
  endfunction

  virtual task run_phase(uvm_phase phase);
    {p}_seq_item tr;
    forever begin
      @(vif.mon_cb);{in_reset}
      tr = {p}_seq_item::type_id::create("tr");
{sample}
      ap.write(tr);
    end
  endtask
endclass
"""

    # ---------------------------------------------------------------- agent
    files[f"{p}_agent.sv"] = _banner(f"{p}_agent", "Sequencer + driver + monitor") + f"""
typedef uvm_sequencer #({p}_seq_item) {p}_sequencer;

class {p}_agent extends uvm_agent;
  `uvm_component_utils({p}_agent)

  {p}_sequencer sqr;
  {p}_driver    drv;
  {p}_monitor   mon;

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  virtual function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    mon = {p}_monitor::type_id::create("mon", this);
    if (get_is_active() == UVM_ACTIVE) begin
      sqr = {p}_sequencer::type_id::create("sqr", this);
      drv = {p}_driver::type_id::create("drv", this);
    end
  endfunction

  virtual function void connect_phase(uvm_phase phase);
    if (get_is_active() == UVM_ACTIVE) drv.seq_item_port.connect(sqr.seq_item_export);
  endfunction
endclass
"""

    # ---------------------------------------------------------------- scoreboard
    files[f"{p}_scoreboard.sv"] = _banner(f"{p}_scoreboard", "Checks DUT outputs against a reference model") + f"""
class {p}_scoreboard extends uvm_scoreboard;
  `uvm_component_utils({p}_scoreboard)

  uvm_analysis_imp #({p}_seq_item, {p}_scoreboard) imp;
  int unsigned n_seen, n_checked, n_errors;

  function new(string name, uvm_component parent);
    super.new(name, parent);
    imp = new("imp", this);
  endfunction

  // TODO: reference model. Return 1 and fill 'exp' when this transaction can be checked.
  virtual function bit predict({p}_seq_item tr, output {p}_seq_item exp);
    exp = null;
    return 0;
  endfunction

  virtual function void write({p}_seq_item tr);
    {p}_seq_item exp;
    n_seen++;
    if (predict(tr, exp)) begin
      n_checked++;
      if (!tr.compare(exp)) begin
        n_errors++;
        `uvm_error("MISMATCH", $sformatf("got %s, expected %s", tr.convert2string(), exp.convert2string()))
      end
    end
  endfunction

  virtual function void report_phase(uvm_phase phase);
    `uvm_info("SCB", $sformatf("%0d transactions seen, %0d checked, %0d mismatches", n_seen, n_checked, n_errors), UVM_LOW)
    if (n_checked == 0) `uvm_warning("SCB", "nothing was checked: implement predict()")
  endfunction
endclass
"""

    # ---------------------------------------------------------------- coverage
    cps = []
    for x in data_in:
        if (x.width or 1) <= 4:
            cps.append(f"    cp_{x.name}: coverpoint tr.{x.name};")
        else:
            cps.append(f"    cp_{x.name}: coverpoint tr.{x.name} {{ option.auto_bin_max = 16; }}")
    files[f"{p}_coverage.sv"] = _banner(f"{p}_coverage", "Functional coverage of the stimulus") + f"""
class {p}_coverage extends uvm_subscriber #({p}_seq_item);
  `uvm_component_utils({p}_coverage)

  {p}_seq_item tr;

  covergroup cg;
    option.per_instance = 1;
{chr(10).join(cps) if cps else "    // no data inputs to cover"}
  endgroup

  function new(string name, uvm_component parent);
    super.new(name, parent);
    cg = new();
  endfunction

  virtual function void write({p}_seq_item t);
    tr = t;
    cg.sample();
  endfunction

  virtual function void report_phase(uvm_phase phase);
    `uvm_info("COV", $sformatf("functional coverage: %0.1f%%", cg.get_inst_coverage()), UVM_LOW)
  endfunction
endclass
"""

    # ---------------------------------------------------------------- env + test
    files[f"{p}_env.sv"] = _banner(f"{p}_env", "Agent + scoreboard + coverage") + f"""
class {p}_env extends uvm_env;
  `uvm_component_utils({p}_env)

  {p}_agent      agt;
  {p}_scoreboard scb;
  {p}_coverage   cov;

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  virtual function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    agt = {p}_agent::type_id::create("agt", this);
    scb = {p}_scoreboard::type_id::create("scb", this);
    cov = {p}_coverage::type_id::create("cov", this);
  endfunction

  virtual function void connect_phase(uvm_phase phase);
    agt.mon.ap.connect(scb.imp);
    agt.mon.ap.connect(cov.analysis_export);
  endfunction
endclass
"""
    files[f"{p}_base_test.sv"] = _banner(f"{p}_base_test", "Runs the random sequence") + f"""
class {p}_base_test extends uvm_test;
  `uvm_component_utils({p}_base_test)

  {p}_env env;

  function new(string name, uvm_component parent);
    super.new(name, parent);
  endfunction

  virtual function void build_phase(uvm_phase phase);
    super.build_phase(phase);
    env = {p}_env::type_id::create("env", this);
  endfunction

  virtual function void end_of_elaboration_phase(uvm_phase phase);
    uvm_top.print_topology();
  endfunction

  virtual task run_phase(uvm_phase phase);
    {p}_base_seq seq = {p}_base_seq::type_id::create("seq");
    phase.raise_objection(this);
    if (!seq.randomize()) `uvm_error("RAND", "sequence randomization failed")
    seq.start(env.agt.sqr);
    repeat (5) @(posedge env.agt.drv.vif.{cname});   // let the last outputs settle
    phase.drop_objection(this);
  endtask
endclass
"""

    # ---------------------------------------------------------------- package
    order = ["seq_item", "sequence", "driver", "monitor", "agent", "scoreboard", "coverage", "env", "base_test"]
    files[f"{p}_pkg.sv"] = _banner(f"{p}_pkg", "Everything the testbench needs, in compile order") + f"""
package {p}_pkg;
  import uvm_pkg::*;
  `include "uvm_macros.svh"

{chr(10).join(f'  `include "{p}_{o}.sv"' for o in order)}
endpackage
"""

    # ---------------------------------------------------------------- tb_top
    conns = []
    for x in module.ports:
        if x.name in [c.name for c in clocks]:
            conns.append(f"    .{x.name}(clk)")
        else:
            conns.append(f"    .{x.name}(vif.{x.name})")
    params = ", ".join(f".{q.name}({q.value if q.value is not None else q.default})" for q in module.parameters if not q.local)
    zero, one = "1'b0", "1'b1"
    rst_init = "\n".join(f"    vif.{r.name} = {zero if reset_active_low(r) else one};" for r in resets)
    rst_rel = "\n".join(f"    vif.{r.name} = {one if reset_active_low(r) else zero};" for r in resets)
    reset_block = f"""
  // reset: active for 5 clocks
  initial begin
{rst_init}
    repeat (5) @(posedge clk);
{rst_rel}
  end
""" if resets else ""
    files["tb_top.sv"] = _banner("tb_top", f"Top level: clock, reset, DUT {module.name} and run_test") + f"""
`timescale 1ns/1ps

module tb_top;
  import uvm_pkg::*;
  `include "uvm_macros.svh"
  import {p}_pkg::*;

  logic clk = 1'b0;
  always #5 clk = ~clk;   // 100 MHz

  {p}_if vif(clk);
{reset_block}
  {module.name} {"#(" + params + ") " if params else ""}dut (
{("," + chr(10)).join(conns)}
  );

  initial begin
    uvm_config_db#(virtual {p}_if)::set(null, "*", "vif", vif);
    run_test("{p}_base_test");
  end

  initial begin
    $dumpfile("tb_top.vcd");
    $dumpvars(0, tb_top);
  end
endmodule
"""

    files["files.f"] = (
        "// Compile order. Add your RTL file(s) on the first line.\n"
        f"// Questa:  vlog -sv +incdir+$UVM_HOME/src $UVM_HOME/src/uvm_pkg.sv -f files.f && vsim -c tb_top +UVM_TESTNAME={p}_base_test -do \"run -all\"\n"
        f"// VCS:     vcs -sverilog -ntb_opts uvm-1.2 -f files.f -R +UVM_TESTNAME={p}_base_test\n"
        f"// Xcelium: xrun -uvm -f files.f +UVM_TESTNAME={p}_base_test\n"
        f"{module.name}.v\n{p}_if.sv\n{p}_pkg.sv\ntb_top.sv\n"
    )
    return {"files": files, "top": module.name, "prefix": p, "notes": notes,
            "clock": clk, "resets": [r.name for r in resets], "inputs": [x.name for x in data_in],
            "outputs": [x.name for x in outputs]}


# ============================================================================ register model

_ACCESS = {  # spec access -> (uvm_reg_field access, volatile, map rights)
    "RW": ("RW", 0, "RW"), "RO": ("RO", 1, "RO"), "WO": ("WO", 0, "WO"), "W1C": ("W1C", 1, "RW"),
}


def uvm_ral(rm):
    blk = _ident(rm.block)
    dw = rm.data_width
    classes = []
    for r in rm.registers:
        acc, volatile, _ = _ACCESS.get(r.access, ("RW", 0, "RW"))
        rand = 1 if acc in ("RW", "WO") else 0
        decl = "\n".join(f"  {'rand ' if rand else ''}uvm_reg_field {f.name};" for f in r.fields)
        build = "\n".join(
            f'    {f.name} = uvm_reg_field::type_id::create("{f.name}");\n'
            f'    {f.name}.configure(this, {f.width}, {f.lsb}, "{acc}", {volatile}, {f.width}\'h{f.reset:X}, 1, {rand}, 0);'
            for f in r.fields)
        desc = f"  // {r.description}\n" if r.description else ""
        classes.append(f"""class {blk}_{r.name.lower()}_reg extends uvm_reg;
  `uvm_object_utils({blk}_{r.name.lower()}_reg)
{desc}
{decl}

  function new(string name = "{r.name.lower()}");
    super.new(name, {dw}, UVM_NO_COVERAGE);
  endfunction

  virtual function void build();
{build}
  endfunction
endclass
""")
    regs_decl = "\n".join(f"  rand {blk}_{r.name.lower()}_reg {r.name.lower()};" for r in rm.registers)
    regs_build = "\n".join(
        f'    {r.name.lower()} = {blk}_{r.name.lower()}_reg::type_id::create("{r.name.lower()}");\n'
        f'    {r.name.lower()}.configure(this, null, "");\n'
        f'    {r.name.lower()}.build();\n'
        f'    default_map.add_reg({r.name.lower()}, \'h{r.offset:X}, "{_ACCESS.get(r.access, ("", 0, "RW"))[2]}");'
        for r in rm.registers)
    files = {}
    files[f"{blk}_reg_model.sv"] = _banner(f"{blk}_reg_model", f"UVM register model of block {rm.block}") + f"""
// Use:  {blk}_reg_block rm = {blk}_reg_block::type_id::create("rm");
//       rm.build(); rm.default_map.set_sequencer(bus_sequencer, adapter);
//       rm.ctrl.write(status, 'h1);  rm.status.read(status, value);

{chr(10).join(classes)}
class {blk}_reg_block extends uvm_reg_block;
  `uvm_object_utils({blk}_reg_block)

{regs_decl}

  function new(string name = "{blk}_reg_block");
    super.new(name, UVM_NO_COVERAGE);
  endfunction

  virtual function void build();
    default_map = create_map("default_map", 'h{rm.base_address:X}, {dw // 8}, UVM_LITTLE_ENDIAN, 1);
{regs_build}
    lock_model();
  endfunction
endclass
"""
    files[f"{blk}_reg_adapter.sv"] = _banner(f"{blk}_reg_adapter", "Connects the register model to a bus agent") + f"""
// A minimal bus transaction. Replace it with your AXI-Lite/APB agent's sequence item.
class {blk}_bus_item extends uvm_sequence_item;
  `uvm_object_utils({blk}_bus_item)
  rand bit                 write;
  rand bit [{rm.addr_width - 1}:0]         addr;
  rand bit [{dw - 1}:0]        data;
  rand bit [{dw // 8 - 1}:0]          strb;
       bit                 error;   // SLVERR/DECERR seen by the driver
  function new(string name = "{blk}_bus_item");
    super.new(name);
  endfunction
endclass

class {blk}_reg_adapter extends uvm_reg_adapter;
  `uvm_object_utils({blk}_reg_adapter)

  function new(string name = "{blk}_reg_adapter");
    super.new(name);
    supports_byte_enable = 1;
    provides_responses   = 0;
  endfunction

  virtual function uvm_sequence_item reg2bus(const ref uvm_reg_bus_op rw);
    {blk}_bus_item item = {blk}_bus_item::type_id::create("item");
    item.write = (rw.kind == UVM_WRITE);
    item.addr  = rw.addr;
    item.data  = rw.data;
    item.strb  = rw.byte_en;
    return item;
  endfunction

  virtual function void bus2reg(uvm_sequence_item bus_item, ref uvm_reg_bus_op rw);
    {blk}_bus_item item;
    if (!$cast(item, bus_item)) `uvm_fatal("ADAPTER", "wrong bus item type")
    rw.kind   = item.write ? UVM_WRITE : UVM_READ;
    rw.addr   = item.addr;
    rw.data   = item.data;
    rw.status = item.error ? UVM_NOT_OK : UVM_IS_OK;
  endfunction
endclass
"""
    files[f"{blk}_ral_pkg.sv"] = _banner(f"{blk}_ral_pkg", "Register model package") + f"""
package {blk}_ral_pkg;
  import uvm_pkg::*;
  `include "uvm_macros.svh"

  `include "{blk}_reg_model.sv"
  `include "{blk}_reg_adapter.sv"
endpackage
"""
    return {"files": files, "block": blk, "registers": len(rm.registers)}
