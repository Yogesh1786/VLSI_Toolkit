"""Generate instantiation templates and testbenches from a parsed Module.

Three outputs:
  * instantiation()   -> paste-ready "dut #(...) u_dut (...);" text
  * verilog_tb()      -> self-running Verilog testbench (clock, reset,
                         random stimulus, VCD dump, monitor)
  * cocotb_test()     -> Python testbench for cocotb (https://www.cocotb.org)

Clock and reset ports are detected from their names:
  clock : clk, clock, clk_i, i_clk, sys_clk, ...
  reset : anything containing "rst" or "reset"; names ending in n/_n/_b/_l
          (rst_n, resetn, rst_b) are treated as active-low.
"""

import re
from datetime import date

# clk, clock, clk_i, i_clk, sys_clk, clk_core, AXI style aclk / s_axi_aclk / m_axil_aclk
_CLOCK_RE = re.compile(
    r"^(clk|clock|aclk|clk_i|i_clk|.*_clk|.*_aclk|clk_\w+|.*_clock)$", re.I
)


def is_clock(port):
    return (
        port.direction == "input"
        and (port.width == 1)
        and bool(_CLOCK_RE.match(port.name))
    )


def is_reset(port):
    n = port.name.lower()
    return (
        port.direction == "input" and port.width == 1 and ("rst" in n or "reset" in n)
    )


def reset_active_low(port):
    return bool(re.search(r"(n|_n|_b|_l|_ni)$", port.name.lower()))


def classify(module):
    """Split input ports into clocks, resets and plain data inputs."""
    clocks = [p for p in module.inputs if is_clock(p)]
    resets = [p for p in module.inputs if is_reset(p) and p not in clocks]
    data = [p for p in module.inputs if p not in clocks and p not in resets]
    return clocks, resets, data


# --------------------------------------------------------------------------
# Instantiation template
# --------------------------------------------------------------------------


def instantiation(module, instance_name=None, indent=""):
    inst = instance_name or f"u_{module.name}"
    params = module.overridable_params
    lines = []
    if params:
        w = max(len(p.name) for p in params)
        lines.append(f"{indent}{module.name} #(")
        for i, p in enumerate(params):
            comma = "," if i < len(params) - 1 else ""
            lines.append(f"{indent}    .{p.name.ljust(w)} ({p.name}){comma}")
        lines.append(f"{indent}) {inst} (")
    else:
        lines.append(f"{indent}{module.name} {inst} (")
    if module.ports:
        w = max(len(p.name) for p in module.ports)
        for i, p in enumerate(module.ports):
            comma = "," if i < len(module.ports) - 1 else " "
            info = f"{p.direction} {p.packed_range}".rstrip()
            lines.append(
                f"{indent}    .{p.name.ljust(w)} ({p.name.ljust(w)}){comma}  // {info}"
            )
    lines.append(f"{indent});")
    return "\n".join(lines)


