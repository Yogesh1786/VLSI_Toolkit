# Verilog testbench
# --------------------------------------------------------------------------


def _random_expr(port):
    """$random is 32 bits; concatenate copies for wider ports."""
    if port.width is not None and port.width > 32:
        copies = (port.width + 31) // 32
        return "{" + ", ".join(["$random"] * copies) + "}"
    return "$random"


def verilog_tb(module, num_cycles=100, clk_period=10, source=None):
    clocks, resets, data_inputs = classify(module)
    tb = f"tb_{module.name}"
    main_clk = clocks[0] if clocks else None
    params = module.overridable_params

    # ---- signal declarations, aligned ----
    decls = []
    for p in module.ports:
        kind = "reg " if p.direction == "input" else "wire"
        sign = "signed " if p.signed else ""
        decls.append((kind, f"{sign}{p.packed_range}".strip(), p.name, p.direction))
    rw = max((len(d[1]) for d in decls), default=0)

    out = []
    a = out.append
    a("`timescale 1ns/1ps")
    a("// " + "=" * 70)
    a(f"// Testbench for '{module.name}'")
    a(
        f"// Auto-generated by VLSI Toolkit on {date.today().isoformat()}"
        + (f" from {source}" if source else "")
    )
    a("// Edit the STIMULUS and CHECKS sections to add real test cases.")
    a("// " + "=" * 70)
    a(f"module {tb};")
    a("")
    a("    // ---------------- Parameters ----------------")
    # Declare every DUT parameter, including localparams: port ranges such
    # as [ADDR_W:0] may refer to them.
    for p in module.parameters:
        note = "  // mirrors DUT localparam" if p.local else ""
        a(f"    localparam {p.name} = {p.default};{note}")
    a(f"    localparam CLK_PERIOD = {clk_period};  // ns")
    a(f"    localparam NUM_CYCLES = {num_cycles};")
    a("")
    a("    // ---------------- DUT signals ----------------")
    for kind, rng, name, direction in decls:
        note = (
            "  // TODO: drive inout with a tri-state buffer"
            if direction == "inout"
            else ""
        )
        a(f"    {kind} {rng.ljust(rw)} {name};{note}")
    a("")
    a("    // ---------------- DUT instance ----------------")
    a(instantiation(module, instance_name="dut", indent="    "))
    a("")

    if clocks:
        a("    // ---------------- Clock generation ----------------")
        for c in clocks:
            a(f"    initial {c.name} = 1'b0;")
            a(f"    always #(CLK_PERIOD/2) {c.name} = ~{c.name};")
        a("")

    a("    // ---------------- Waveform dump (open with GTKWave) ----------------")
    a("    initial begin")
    a(f'        $dumpfile("{tb}.vcd");')
    a(f"        $dumpvars(0, {tb});")
    a("    end")
    a("")

    wait_step = f"@(negedge {main_clk.name})" if main_clk else "#(CLK_PERIOD)"
    wait_n = (
        (lambda n: f"repeat ({n}) @(posedge {main_clk.name});")
        if main_clk
        else (lambda n: f"#({n}*CLK_PERIOD);")
    )

    a("    // ---------------- Stimulus ----------------")
    a("    integer i;")
    a("    initial begin")
    a("        // 1. Initialise all inputs")
    for p in data_inputs:
        a(f"        {p.name} = 0;")
    if resets:
        a("")
        a("        // 2. Apply reset")
        for r in resets:
            a(
                f"        {r.name} = 1'b{'0' if reset_active_low(r) else '1'};  // assert ({'active-low' if reset_active_low(r) else 'active-high'})"
            )
        a(f"        {wait_n(5)}")
        for r in resets:
            a(
                f"        {r.name} = 1'b{'1' if reset_active_low(r) else '0'};  // release"
            )
    a("")
    a("        // 3. Random stimulus  (replace with directed tests as needed)")
    a("        for (i = 0; i < NUM_CYCLES; i = i + 1) begin")
    a(f"            {wait_step};")
    for p in data_inputs:
        a(f"            {p.name} = {_random_expr(p)};")
    a("        end")
    a("")
    a(f"        {wait_n(5)}")
    a('        $display("[%0t] TEST DONE", $time);')
    a("        $finish;")
    a("    end")
    a("")

    if module.outputs:
        a("    // ---------------- Monitor / CHECKS ----------------")
        fmt = " ".join(f"{p.name}=%h" for p in module.outputs)
        args = ", ".join(p.name for p in module.outputs)
        trigger = f"posedge {main_clk.name}" if main_clk else "*"
        a(f"    always @({trigger}) begin")
        a(f'        $display("[%0t] {fmt}", $time, {args});')
        a("        // TODO: compare outputs against a reference model, e.g.")
        a(
            '        // if (out !== expected) $error("Mismatch: out=%h exp=%h", out, expected);'
        )
        a("    end")
        a("")
    a("endmodule")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# cocotb (Python) testbench
# --------------------------------------------------------------------------


def cocotb_test(module, source_path, num_cycles=100, clk_period=10, simulator="icarus"):
    clocks, resets, data_inputs = classify(module)
    main_clk = clocks[0] if clocks else None
    test_mod = f"test_{module.name}"
    src = str(source_path).replace("\\", "/")

    out = []
    a = out.append
    a(f'"""cocotb testbench for \'{module.name}\' (auto-generated by VLSI Toolkit).')
    a("")
    a("Requirements:  pip install cocotb   +  a simulator such as Icarus Verilog")
    a(f"Run:           python {test_mod}.py")
    a('"""')
    a("")
    a("import random")
    a("from pathlib import Path")
    a("")
    a("import cocotb")
    a("from cocotb.clock import Clock")
    a("from cocotb.triggers import ClockCycles, FallingEdge, Timer")
    a("")
    a("")
    a("@cocotb.test()")
    a(f"async def test_{module.name}_random(dut):")
    a(f'    """Reset the DUT, then drive random values for {num_cycles} cycles."""')
    for c in clocks:
        a(
            f'    cocotb.start_soon(Clock(dut.{c.name}, {clk_period}, unit="ns").start())'
        )
    a("")
    a("    # 1. Initialise inputs")
    for p in data_inputs:
        a(f"    dut.{p.name}.value = 0")
    if resets:
        a("")
        a("    # 2. Reset")
        for r in resets:
            a(f"    dut.{r.name}.value = {0 if reset_active_low(r) else 1}")
        a(
            f"    await ClockCycles(dut.{main_clk.name}, 5)"
            if main_clk
            else f'    await Timer({5 * clk_period}, unit="ns")'
        )
        for r in resets:
            a(f"    dut.{r.name}.value = {1 if reset_active_low(r) else 0}")
    a("")
    a("    # 3. Random stimulus")
    a(f"    for cycle in range({num_cycles}):")
    a(
        f"        await FallingEdge(dut.{main_clk.name})"
        if main_clk
        else f'        await Timer({clk_period}, unit="ns")'
    )
    for p in data_inputs:
        a(f"        dut.{p.name}.value = random.getrandbits(len(dut.{p.name}))")
    if module.outputs:
        a("        # TODO: check outputs against a Python reference model, e.g.")
        a(
            f'        # assert dut.{module.outputs[0].name}.value == expected, f"cycle {{cycle}}: mismatch"'
        )
    a("")
    a('    dut._log.info("Random test finished")')
    a("")
    a("")
    a(f"def run_{module.name}():")
    a(
        '    """Build and run the simulation using the cocotb Python runner (no Makefile needed)."""'
    )
    a("    from cocotb_tools.runner import get_runner")
    a("")
    a(f'    runner = get_runner("{simulator}")')
    a(
        f'    runner.build(sources=[Path(r"{src}")], hdl_toplevel="{module.name}", always=True)'
    )
    a(
        f'    runner.test(hdl_toplevel="{module.name}", test_module="{test_mod}", test_dir=Path(__file__).parent)'
    )
    a("")
    a("")
    a('if __name__ == "__main__":')
    a(f"    run_{module.name}()")
    return "\n".join(out) + "\n"
